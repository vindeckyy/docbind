import { describe, expect, it } from "vitest";
import {
  discoverCode,
  discoverDocs,
  findPackageRoot,
  isGeneratedDoc,
  modulePathFor,
  projectRelative,
  readPackageMarker,
} from "../src/discover.js";
import { DEFAULT_CONFIG, parseConfig } from "../src/config.js";
import { join } from "node:path";
import { tempProject } from "./helpers.js";

describe("discovery", () => {
  it("discovers markdown and skips configured and generated files", () => {
    const root = tempProject({
      "README.md": "# readme",
      "docs/a.md": "# a",
      "docs/nested/b.md": "# b",
      "CHANGELOG.md": "# old",
      "node_modules/pkg/readme.md": "# pkg",
      "docs/generated.md": "<!-- generated -->\n# x",
    });
    const files = discoverDocs(root, DEFAULT_CONFIG);
    expect(files).toContain("README.md");
    expect(files).toContain("docs/a.md");
    expect(files).toContain("docs/nested/b.md");
    expect(files).not.toContain("CHANGELOG.md");
    expect(files).not.toContain("node_modules/pkg/readme.md");
    expect(files).not.toContain("docs/generated.md");
  });

  it("respects .gitignore", () => {
    const root = tempProject({
      ".gitignore": "ignored.md\nignored.ts\n",
      "kept.md": "# kept",
      "ignored.md": "# ignored",
      "kept.ts": "export const kept = 1;",
      "ignored.ts": "export const ignored = 1;",
    });
    expect(discoverDocs(root, DEFAULT_CONFIG)).toEqual(["kept.md"]);
    expect(discoverCode(root, DEFAULT_CONFIG)).toEqual(["kept.ts"]);
  });

  it("discovers code by language and ignores noise", () => {
    const root = tempProject({
      "src/a.ts": "export const a = 1;",
      "src/b.py": "b = 1",
      "src/c.js": "export const c = 1;",
      "src/lib.rs": "pub fn rust_item() {}",
      "src/main.go": "package main",
      "src/d.min.js": "var d=1;",
      "node_modules/x/index.js": "x",
    });
    const both = discoverCode(root, DEFAULT_CONFIG);
    expect(both).toContain("src/a.ts");
    expect(both).toContain("src/b.py");
    expect(both).toContain("src/c.js");
    expect(both).toContain("src/lib.rs");
    expect(both).not.toContain("src/main.go");
    expect(both).not.toContain("src/d.min.js");
    expect(both).not.toContain("node_modules/x/index.js");

    const tsOnly = discoverCode(root, parseConfig({ languages: { python: false } }));
    expect(tsOnly).not.toContain("src/b.py");
    const pyOnly = discoverCode(root, parseConfig({ languages: { typescript: false } }));
    expect(pyOnly).toEqual(expect.arrayContaining(["src/b.py", "src/lib.rs"]));
    const withGo = discoverCode(root, parseConfig({ languages: { go: true } }));
    expect(withGo).toContain("src/main.go");
    const noRust = discoverCode(root, parseConfig({ languages: { rust: false } }));
    expect(noRust).not.toContain("src/lib.rs");
  });

  it("recognizes generated headers", () => {
    expect(isGeneratedDoc("<!-- generated by tool -->")).toBe(true);
    expect(isGeneratedDoc("<!-- do not edit -->")).toBe(true);
    expect(isGeneratedDoc("# Generated\n")).toBe(true);
    expect(isGeneratedDoc("generated by script")).toBe(true);
    expect(isGeneratedDoc("# Real docs\n\nGenerated values are examples.")).toBe(false);
  });

  it("reads every package marker", () => {
    expect(readPackageMarker(tempProject({ "package.json": JSON.stringify({ name: "app" }) }))?.name).toBe("app");
    expect(readPackageMarker(tempProject({ "pyproject.toml": '[project]\nname = "pyapp"\n' }))?.name).toBe("pyapp");
    expect(readPackageMarker(tempProject({ "Cargo.toml": '[package]\nname = "crate"\n' }))?.name).toBe("crate");
    expect(readPackageMarker(tempProject({ "go.mod": "module example.com/goapp\n" }))?.name).toBe("example.com/goapp");
    const invalid = tempProject({ "package.json": "{" });
    expect(readPackageMarker(invalid)?.name).toBe(invalid.split("/").pop());
    const unnamed = tempProject({ "package.json": "{}" });
    expect(readPackageMarker(unnamed)?.name).toBe(unnamed.split("/").pop());
    const noPyName = tempProject({ "pyproject.toml": "[project]" });
    expect(readPackageMarker(noPyName)?.name).toBe(noPyName.split("/").pop());
    const noCargoName = tempProject({ "Cargo.toml": "[package]" });
    expect(readPackageMarker(noCargoName)?.name).toBe(noCargoName.split("/").pop());
    const noGoModule = tempProject({ "go.mod": "go 1.24" });
    expect(readPackageMarker(noGoModule)?.name).toBe(noGoModule.split("/").pop());
    expect(readPackageMarker(tempProject({}))).toBeUndefined();
  });

  it("finds the nearest package root", () => {
    const root = tempProject({
      "package.json": JSON.stringify({ name: "root" }),
      "packages/app/package.json": JSON.stringify({ name: "app" }),
      "packages/app/src/a.ts": "export const a = 1;",
      "packages/lib/src/b.ts": "export const b = 1;",
    });
    expect(findPackageRoot(root, "packages/app/src/a.ts")).toMatchObject({ name: "app" });
    expect(findPackageRoot(root, "packages/lib/src/b.ts")).toMatchObject({ name: "root" });
    expect(findPackageRoot(root, "outside.ts")).toMatchObject({ name: "root" });
    expect(findPackageRoot(tempProject({ "a.ts": "" }), "a.ts")).toMatchObject({ name: expect.any(String) });
  });

  it("builds module paths", () => {
    const root = tempProject({ "src/users/index.ts": "export const x = 1;" });
    const absolute = join(root, "src/users/index.ts");
    expect(modulePathFor(root, absolute)).toBe("src/users");
    expect(modulePathFor(root, "src/users/index.ts")).toBe("src/users");
    expect(modulePathFor(root, join(root, "src/types.d.ts"))).toBe("src/types");
    expect(modulePathFor(root, join(root, "src/users.py"))).toBe("src/users");
    expect(modulePathFor(root, root)).toBe("index");
  });

  it("makes project-relative paths", () => {
    const root = tempProject({ "a/b.md": "x" });
    expect(projectRelative(root, "a/b.md")).toBe("a/b.md");
    expect(projectRelative(root, join(root, "a/b.md"))).toBe("a/b.md");
  });
});
