import { readFileSync } from "node:fs";
import { basename, dirname, isAbsolute, join, relative } from "node:path";
import { globSync } from "tinyglobby";
import ignore from "ignore";
import type { Config } from "./types.js";

export interface PackageInfo {
  root: string;
  name: string;
}

const PACKAGE_MARKERS = ["package.json", "pyproject.toml", "Cargo.toml", "go.mod"];

function gitignoreFilter(root: string): ((path: string) => boolean) | undefined {
  try {
    const matcher = ignore().add(readFileSync(join(root, ".gitignore"), "utf8"));
    return (path: string) => !matcher.ignores(path);
  } catch {
    return undefined;
  }
}

export function discoverDocs(root: string, config: Config): string[] {
  const files = globSync(config.docs, {
    cwd: root,
    ignore: config.exclude,
    onlyFiles: true,
    absolute: false,
    dot: false,
  }).sort();
  const keep = gitignoreFilter(root);
  return files.filter((file) => {
    if (keep && !keep(file)) return false;
    try {
      return !isGeneratedDoc(readFileSync(join(root, file), "utf8"));
    } catch {
      return true;
    }
  });
}

export function discoverCode(root: string, config: Config): string[] {
  const patterns: string[] = [];
  if (config.languages.typescript) {
    patterns.push("**/*.{ts,tsx,js,jsx,mjs,cjs}");
  }
  if (config.languages.python) {
    patterns.push("**/*.py");
  }
  if (config.languages.rust) {
    patterns.push("**/*.rs");
  }
  if (config.languages.go) {
    patterns.push("**/*.go");
  }
  const files = globSync(patterns, {
    cwd: root,
    ignore: [
      ...config.exclude,
      "**/node_modules/**",
      "**/*.min.js",
      "**/*.d.ts.map",
      "**/*.test.{ts,tsx,js,jsx}",
      "**/*.spec.{ts,tsx,js,jsx}",
      "**/__tests__/**",
      "**/test/**",
      "**/tests/**",
      "**/test_*.py",
      "**/*_test.py",
    ],
    onlyFiles: true,
    absolute: false,
    dot: false,
  }).sort();
  const keep = gitignoreFilter(root);
  return keep ? files.filter((file) => keep(file)) : files;
}

export function isGeneratedDoc(text: string): boolean {
  const head = text.split(/\r?\n/u).slice(0, 5).join("\n");
  return /<!--\s*(generated|autogenerated|do not edit)/iu.test(head) ||
    /^\s*#\s*generated\b/imu.test(head) ||
    /^\s*generated by\b/imu.test(head);
}

export function readPackageMarker(directory: string): PackageInfo | undefined {
  for (const marker of PACKAGE_MARKERS) {
    const path = join(directory, marker);
    let text: string;
    try {
      text = readFileSync(path, "utf8");
    } catch {
      continue;
    }
    if (marker === "package.json") {
      try {
        const parsed = JSON.parse(text) as { name?: unknown };
        if (typeof parsed.name === "string" && parsed.name.length > 0) {
          return { root: directory, name: parsed.name };
        }
      } catch {
        return { root: directory, name: basename(directory) };
      }
    }
    if (marker === "pyproject.toml") {
      const match = /^\s*name\s*=\s*"([^"]+)"/mu.exec(text);
      if (match?.[1]) return { root: directory, name: match[1] };
    }
    if (marker === "Cargo.toml") {
      const match = /^\s*name\s*=\s*"([^"]+)"/mu.exec(text);
      if (match?.[1]) return { root: directory, name: match[1] };
    }
    if (marker === "go.mod") {
      const match = /^\s*module\s+(\S+)/mu.exec(text);
      if (match?.[1]) return { root: directory, name: match[1] };
    }
    return { root: directory, name: basename(directory) };
  }
  return undefined;
}

export function findPackageRoot(root: string, filePath: string): PackageInfo {
  const absoluteRoot = join(root);
  let directory = dirname(join(root, filePath));
  while (directory.startsWith(absoluteRoot)) {
    const found = readPackageMarker(directory);
    if (found) return found;
    const parent = dirname(directory);
    if (parent === directory) break;
    directory = parent;
  }
  return { root: absoluteRoot, name: basename(root) };
}

export function modulePathFor(packageRoot: string, filePath: string): string {
  const absolutePath = isAbsolute(filePath) ? filePath : join(packageRoot, filePath);
  const relativePath = relative(packageRoot, absolutePath)
    .replace(/\\/gu, "/")
    .replace(/\.(?:d\.)?[cm]?[jt]sx?$/u, "")
    .replace(/\.py$/u, "")
    .replace(/\.rs$/u, "")
    .replace(/\.go$/u, "")
    .replace(/\/index$/u, "");
  return relativePath.length === 0 ? "index" : relativePath;
}

export function projectRelative(root: string, absoluteOrRelative: string): string {
  const absolute = isAbsolute(absoluteOrRelative) ? absoluteOrRelative : join(root, absoluteOrRelative);
  return relative(root, absolute).replace(/\\/gu, "/");
}
